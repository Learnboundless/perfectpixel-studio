  s = s.replace(/자동 재시도 후에도 프레임 수가 다릅니다 \(요청 (\d+)개 → 추출 (\d+)개\)\. 가장 근접한 결과를 표시합니다\./g, "自动重试后帧数仍不一致（请求 $1 帧，提取 $2 帧）。已显示最接近的结果。");
