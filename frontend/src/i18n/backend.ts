export function isBackendCancel(text: string): boolean {
  return text.includes("취소") || text.includes("取消") || text.toLowerCase().includes("canceled");
}

export function isCopyrightRestrictionError(input: unknown): boolean {
  return COPYRIGHT_RESTRICTION_RE.test(String(input ?? ""));
}

